# gf_resid_fun() is generated by ggformula::layer_factory() now, like every
# other layer in this package. These are the contract: what the generated
# function has to keep doing that the bespoke one did, and the things the
# generated one could lose in silence.

test_that("a function given positionally lands where a function given by name does", {
  # `layer_factory()` binds the second positional argument to `gformula`, and
  # `gf_resid_fun(p, f)` is the spelling in every test, example and lesson
  df <- data.frame(X = 1:10, Y = 2 + 3 * (1:10))
  p <- gf_point(Y ~ X, data = df)
  my_fun <- function(x) 2 + 3 * x

  positional <- suppressMessages(gf_resid_fun(p, my_fun))
  named <- suppressMessages(gf_resid_fun(p, fun = my_fun))

  expect_equal(layer_index(positional, "resid"), 2L)
  expect_equal(layer_index(named, "resid"), 2L)
  expect_equal(
    ggplot2::ggplot_build(positional)$data[[2]],
    ggplot2::ggplot_build(named)$data[[2]]
  )
  expect_equal(ggplot2::ggplot_build(positional)$data[[2]]$yend, my_fun(df$X))
})

test_that("a non-function is refused as a function, whichever way it is written", {
  # the recovery moves position 2 into `fun` unconditionally, with no
  # `is.function()` test: a formula that failed such a test would stay in
  # `gformula` and die inside ggformula's own formula parsing, which is a
  # different answer to the same mistake than the one this has always given
  p <- gf_point(Thumb ~ Height, data = Fingers)
  model <- lm(Thumb ~ Height, data = Fingers)

  for (bad in list(model, Thumb ~ Height, 3, "nope")) {
    expect_error(suppressMessages(gf_resid_fun(p, bad)), 'could not find function "fun"')
    expect_error(suppressMessages(gf_resid_fun(p, fun = bad)), 'could not find function "fun"')
  }
})


test_that("a stray positional argument gets ggformula's own refusal, not one of ours", {
  # the released signature was `gf_resid_fun(plot, fun, linewidth = 0.2, ...)`,
  # and the third position really worked until this conversion. The generated
  # third formal is `data`, and `pre` fills it only when the caller left it
  # alone, so a stray third argument reaches ggformula and is refused exactly as
  # it is for any other gf_ function. This package adds no rule of its own.
  p <- gf_point(Thumb ~ Height, data = Fingers)

  expect_error(gf_resid_fun(p, function(x) x, 2), "must be a <data.frame>")
  expect_error(gf_point(Thumb ~ Height, Fingers, 0.5), "must be a <data.frame>")

  # an unusable extra is silent, the same as a misspelled parameter
  expect_no_error(suppressMessages(gf_resid_fun(p, function(x) x, nonesuch = 1)))
  expect_no_warning(suppressMessages(gf_resid_fun(p, function(x) x, nonesuch = 1)))
})


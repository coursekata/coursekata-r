test_that("a residual draws with its own geom, stat and position whatever is asked for", {
  p <- gf_point(Thumb ~ Height, data = Fingers)

  expect_no_warning(
    asked <- suppressMessages(
      gf_resid_fun(p, function(x) x, geom = "segment", stat = "identity", position = "dodge")

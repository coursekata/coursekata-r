test_that("a discrete x reaches the function as the factor the plot draws", {
  # the one place a function-measured residual can genuinely misbehave: the x
  # quosure evaluates to a factor, so an arithmetic function predicts NA
  # everywhere and only a function that coerces draws anything
  p <- gf_point(Thumb ~ Sex, data = Fingers)

  # ggplot2 4.0 carries the arithmetic-on-a-factor NAs through to the layer and
  # warns; 3.5.2's continuous scale refuses them before the layer is built. Both
  # reject the nonsense, at different depths, so only the version that lets it
  # reach the data can be asked what the data holds.
  # WHEN THE FLOOR MOVES TO 4.0: delete this skip.
  skip_if_not(
    utils::packageVersion("ggplot2") >= "4.0.0",
    "ggplot2 3.5.2 refuses a factor at the scale; see R/compat-ggplot2.R"
  )

  expect_warning(
    arithmetic <- ggplot2::ggplot_build(
      suppressMessages(gf_resid_fun(p, function(x) 0.5 * x))
    ),
    "not meaningful for factors"
  )
  expect_true(all(is.na(arithmetic$data[[2]]$yend)))

  coercing <- suppressMessages(gf_resid_fun(p, function(x) 40 + 10 * as.numeric(x)))
  expect_equal(
    ggplot2::ggplot_build(coercing)$data[[2]]$yend,
    40 + 10 * as.numeric(Fingers$Sex)
  )
})

test_that("an unusable name is answered the way the family the caller wrote answers it", {
  # a `gf_` function discards it in silence like `gf_point()` beneath it in the
  # pipe; a layer assembled the ggplot2 way warns on its own, because
  # `resid_layer_fun()` passes `check.param` through instead of overriding it
  p <- gf_point(Thumb ~ Height, data = Fingers)
  expect_no_warning(suppressMessages(gf_resid_fun(p, function(x) x, colr = "red")))

  fitted <- transform(Fingers, .fitted = Fingers$Height)
  expect_warning(
    ggplot2::ggplot_build(
      p + ggplot2::layer(
        geom = GeomResid, stat = StatResid, position = "identity",
        data = fitted, mapping = ggplot2::aes(yend = .data$.fitted),
        params = list(nonesuch = 1)
      )
    ),
    "unknown parameters"
  )
})
test_that("a residual stays on the point it belongs to when the plot jitters", {
  # the residual declares the same jitter the points layer carries, seed and all,
  # so both layers compute the same offsets independently. Nothing is replayed:
  # an offset is a function of the seed and the rows, and both layers have both
  set.seed(7)
  p <- gf_jitter(Thumb ~ Sex, data = Fingers, width = .2) %>%
    gf_resid_fun(function(x) 60)

  points <- ggplot2::layer_grob(p, 1)[[1]]
  segments <- ggplot2::layer_grob(p, layer_index(p, "resid"))[[1]]

  expect_equal(as.numeric(segments$x0), as.numeric(points$x))
  expect_equal(as.numeric(segments$y1), as.numeric(points$y))
})

test_that("what to draw is removed from the layer's parameters, however it was spelled", {
  # `fun` genuinely reaches the layer function in `params` when the caller wrote
  # `fun =` and not when they wrote it positionally, so the two spellings only
  # build the identical layer because this helper removes it. Handed
  # `check.param = TRUE` the removal is visible; the last two expectations are
  # the other half of the same contract -- `check.param` is passed through, not
  # overridden, so a name nothing claims warns the ggplot2 way and is silent the
  # ggformula way.
  aes0 <- ggplot2::aes(yend = .data$.fitted)
  build <- function(params, check.param) {
    coursekata:::resid_layer_fun("resid", aes0)(
      GeomResid, StatResid, "identity",
      params = params, mapping = aes0,
      data = transform(Fingers, .fitted = Fingers$Height),
      check.param = check.param
    )
  }

  expect_no_warning(build(list(fun = function(x) x, linewidth = 0.2), TRUE))
  expect_no_warning(build(list(model = lm(Thumb ~ Height, data = Fingers)), TRUE))
  expect_warning(build(list(nonesuch = 1), TRUE), "unknown parameters")
  expect_no_warning(build(list(nonesuch = 1), FALSE))
})

test_that("the experimental signal fires on a real call and not on a bare help call", {
  # the one contract no fingerprint can see: `lifecycle::signal_stage()` emits
  # nothing observable at 1.0.5, so a mocked binding is the only gate on where
  # the signal sits -- behind the help gate, and first inside it
  p <- gf_point(Thumb ~ Height, data = Fingers)
  f <- function(x) x + 20
  signalled <- character()
  local_mocked_bindings(
    signal_stage = function(stage, what, with = NULL, env = NULL) {
      signalled <<- c(signalled, paste0(stage, ":", what))
      invisible()
    },
    .package = "lifecycle"
  )

  suppressMessages(gf_resid_fun(p, f))
  expect_equal(signalled, "experimental:gf_resid_fun()")

  # a call that is about to be refused is still a call
  signalled <- character()
  try(suppressMessages(gf_resid_fun(Fingers, f)), silent = TRUE)
  expect_equal(signalled, "experimental:gf_resid_fun()")

  # asking a function what it takes is not using it
  signalled <- character()
  suppressMessages(gf_resid_fun())
  suppressMessages(gf_resid_fun(p, f, show.help = TRUE))
  expect_equal(signalled, character())
})

test_that("a function that predicts nothing for a row drops that row and says so", {
  # `GeomResid$handle_na` names the end that arrived, because the inherited drop
  # reads `required_aes` literally and `"xend|yend"` is not a column
  p <- gf_point(Thumb ~ Height, data = Fingers)
  drawn <- suppressMessages(gf_resid_fun(p, function(x) ifelse(x > 65, NA_real_, 60)))

  expect_warning(
    grob <- ggplot2::layer_grob(drawn, layer_index(drawn, "resid"))[[1]],
    "geom_resid"
  )
  expect_equal(length(grob$x0), sum(Fingers$Height <= 65))
})
